function buildPoly(pts){
  const p = pts.map(([lo, la]) => geo(lo, la));
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for(const [x, y] of p){ minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
  return { p, minX, minY, maxX, maxY };
}
const MAINLAND = buildPoly(MAINLAND_RAW);
const CARVES = Object.values(CARVES_RAW).map(buildPoly);
const ISLANDS = Object.values(ISLANDS_RAW).map(buildPoly);

function inPoly(P, x, y){
  if(x < P.minX || x > P.maxX || y < P.minY || y > P.maxY) return false;
  const p = P.p; let inside = false;
  for(let i = 0, j = p.length - 1; i < p.length; j = i++){
    const [xi, yi] = p[i], [xj, yj] = p[j];
    if(((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi)) inside = !inside;
  }
  return inside;
}

// 이 점이 육지인가?
function isLand(x, y){
  if(x < 0 || y < 0 || x > WORLD_W || y > WORLD_H) return true;
  for(const I of ISLANDS) if(inPoly(I, x, y)) return true;
  if(!inPoly(MAINLAND, x, y)) return false;
  for(const C of CARVES) if(inPoly(C, x, y)) return false;
  return true;
}

