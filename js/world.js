function blob(lon, lat, rx, ry, n = 12){
  const pts = [];
  for(let i = 0; i < n; i++){
    const a = i / n * Math.PI * 2, k = 1 + 0.12 * Math.sin(i * 2.3 + lon);
    pts.push([lon + Math.cos(a) * rx * k, lat + Math.sin(a) * ry * k]);
  }
  return pts;
}

